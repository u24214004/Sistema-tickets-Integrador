CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc VARCHAR(11) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL
);
CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('INTERNO', 'CLIENTE')),
    company_id BIGINT REFERENCES companies(id),
    CHECK ((role = 'CLIENTE' AND company_id IS NOT NULL) OR (role = 'INTERNO' AND company_id IS NULL))
);
CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    requester_id BIGINT NOT NULL REFERENCES app_users(id),
    title VARCHAR(150) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    severity VARCHAR(20) NOT NULL CHECK (severity IN ('CRITICA', 'ALTA', 'MEDIA', 'BAJA')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ABIERTO', 'EN_PROCESO', 'EN_ESPERA', 'RESUELTO')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_tickets_company_created ON tickets(company_id, created_at);
CREATE INDEX idx_tickets_status ON tickets(status);
CREATE TABLE ticket_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    actor_id BIGINT NOT NULL REFERENCES app_users(id),
    action VARCHAR(50) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_events_ticket ON ticket_events(ticket_id);
